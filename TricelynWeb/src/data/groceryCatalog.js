export function getProductDetails(id) {
  if (!id) return buildProductDetailsPayload(ALL_CATALOG_PRODUCTS[0], ALL_CATALOG_PRODUCTS);
  const idStr = String(id).toLowerCase();
  
  // Exact match by _id, id, or slug
  let found = ALL_CATALOG_PRODUCTS.find(p => 
    p._id === id || 
    p.id === id || 
    p.slug === id ||
    (p.slug && p.slug.toLowerCase() === idStr)
  );

  // Partial or fuzzy match by name
  if (!found) {
    found = ALL_CATALOG_PRODUCTS.find(p => {
      const nameNorm = (p.name || '').toLowerCase().replace(/[^a-z0-9]+/g, '-');
      return (
        nameNorm === idStr ||
        nameNorm.includes(idStr) ||
        idStr.includes(nameNorm) ||
        (p.name && p.name.toLowerCase() === idStr)
      );
    });
  }

  // Check in BEST_SELLERS as well
  if (!found) {
    found = BEST_SELLERS.find(p => p._id === id || p.id === id || p.name?.toLowerCase() === idStr);
  }

  // Graceful fallback to first product so user never gets broken page
  if (!found) {
    found = ALL_CATALOG_PRODUCTS[0];
  }

  return buildProductDetailsPayload(found, ALL_CATALOG_PRODUCTS);
}
